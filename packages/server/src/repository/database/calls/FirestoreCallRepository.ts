import type { Call } from '@recall/shared';
import { Firebase } from '../utils';
import type { CallRepository } from './CallRepository';

/**
 * Firebase implementation of call repository
 */
export class FirestoreCallRepository implements CallRepository {
  static readonly COLLECTION = 'calls';

  /**
   * Get all calls, ordered by creation time in descending order
   * @returns a list of all calls
   */
  async getAllCalls(): Promise<Call[]> {
    const db = Firebase.getInstance();
    const snapshot = await db
      .collection(FirestoreCallRepository.COLLECTION)
      .orderBy('createdAt', 'desc')
      .get();
    return snapshot.docs.map((doc) => doc.data() as Call);
  }

  /**
   * Gets a call with a given ID
   * @param callId - The id of the call to get
   * @returns the call object
   */
  async getCall(callId: string): Promise<Call> {
    const db = Firebase.getInstance();
    const docRef = db.collection(FirestoreCallRepository.COLLECTION).doc(callId);
    const snapshot = await docRef.get();
    return snapshot.data() as Call;
  }

  /**
   * Adds a call with an autogenerated id
   * @param call - The call to add
   * @returns the autogenerated id of the call
   */
  async addCall(call: Omit<Call, 'id'>): Promise<string> {
    const db = Firebase.getInstance();
    const collectionRef = db.collection(FirestoreCallRepository.COLLECTION);

    const docRef = await collectionRef.add(call);
    return docRef.id;
  }

  /**
   * Inserts a call object, overwriting if a call with the same ID already exists.
   * @param call - The call to insert or overwrite
   */
  async setCall(call: Call): Promise<void> {
    const db = Firebase.getInstance();
    const docRef = db.collection(FirestoreCallRepository.COLLECTION).doc(call.id);
    await docRef.set(call);
  }

  /**
   * Deletes a call by its id
   * @param callId - The id of the call to delete
   */
  async deleteCall(callId: string): Promise<void> {
    const db = Firebase.getInstance();
    const docRef = db.collection(FirestoreCallRepository.COLLECTION).doc(callId);
    await docRef.delete();
  }
}
