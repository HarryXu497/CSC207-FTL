/**
 * In memory implementation of the data layer
 */
import { NotFoundError } from 'src/errors';
import type { CallRepository } from './CallRepository';
import type { Call } from 'src/entities';

/** Demo rows */
const SEED: Call[] = [
  {
    id: 'call-1001',
    customerName: 'Priya Raman',
    topic: 'Damaged delivery, replacement refused',
    createdAt: '2026-09-26T14:12:00.000Z',
  },
  {
    id: 'call-1002',
    customerName: 'Dana Olofsson',
    topic: 'Account lockout before a deadline',
    createdAt: '2026-09-28T16:05:00.000Z',
  },
];

export class InMemoryCallRepository implements CallRepository {
  private readonly calls = new Map<string, Call>();

  constructor(seed: Call[] = SEED) {
    for (const call of seed) {
      this.calls.set(call.id, call);
    }
  }

  /**
   * Get all calls, ordered by creation time in descending order
   * @returns a list of all calls
   */
  async getAllCalls(): Promise<Call[]> {
    return [...this.calls.values()].sort((a, b) => b.createdAt.localeCompare(a.createdAt));
  }

  /**
   * Gets a call with a given ID
   * @param callId - The id of the call to get
   * @returns the call object
   */
  async getCall(callId: string): Promise<Call> {
    const call = this.calls.get(callId);
    if (!call) {
      throw new NotFoundError('Call', callId);
    }

    return call;
  }

  /**
   * Adds a call with an autogenerated id
   * @param call - The call to add
   * @returns the autogenerated id of the call
   */
  async addCall(call: Omit<Call, 'id'>): Promise<string> {
    const generatedId = crypto.randomUUID();
    this.calls.set(generatedId, { id: generatedId, ...call });
    return generatedId;
  }

  /**
   * Inserts a call object, overwriting if a call with the same ID already exists.
   * @param call - The call to insert or overwrite
   */
  async setCall(call: Call): Promise<void> {
    this.calls.set(call.id, call);
  }

  /**
   * Deletes a call by its id
   * @param callId - The id of the call to delete
   */
  async deleteCall(callId: string): Promise<void> {
    this.calls.delete(callId);
  }
}
